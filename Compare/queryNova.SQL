        EXEC LX_GERA_IMPOSTOS_SAIDA @FILIAL, @NF_NUMERO, @SERIE_NF, 0, 1, 1 
    END TRY
    BEGIN CATCH
        SELECT @MENSAGEM = 'IMPOSTOS:' + ERROR_MESSAGE()
        ROLLBACK
        UPDATE CSM_NOTAS_SERVICO SET MENSAGEM = @MENSAGEM WHERE ID_NOTA = @ID_NOTA
        GOTO PROXIMO
    END CATCH

    IF (SELECT COUNT(1) FROM FATURAMENTO_IMPOSTO WHERE  FILIAL = @FILIAL AND  NF_SAIDA=@NF_NUMERO AND SERIE_NF=@SERIE_NF AND VALOR_IMPOSTO < 10 AND ID_IMPOSTO = 20) > 0
    BEGIN
        DELETE FROM FATURAMENTO_IMPOSTO WHERE  FILIAL = @FILIAL AND  NF_SAIDA=@NF_NUMERO AND SERIE_NF=@SERIE_NF AND VALOR_IMPOSTO < 10 AND ID_IMPOSTO = 20
        UPDATE FATURAMENTO SET  VALOR_IMPOSTO_AGREGAR = 0, VALOR_TOTAL = VALOR_SUB_ITENS
		    WHERE  FILIAL = @FILIAL AND  NF_SAIDA=@NF_NUMERO AND SERIE_NF=@SERIE_NF
    END

    BEGIN TRY
        EXEC    LX_CTB_INTEGRAR_FATURAMENTO @FILIAL = @FILIAL, @NF_SAIDA = @NF_NUMERO, @SERIE_NF = @SERIE_NF
    END TRY
    
    BEGIN CATCH
        SELECT @MENSAGEM = 'CONTABILIZACAO:' + ERROR_MESSAGE()
        ROLLBACK
        UPDATE CSM_NOTAS_SERVICO SET MENSAGEM = @MENSAGEM WHERE ID_NOTA = @ID_NOTA
        GOTO PROXIMO
    END CATCH

    SELECT @MENSAGEM = 'NOTA PROCESSADA'

    UPDATE CSM_NOTAS_SERVICO SET NF_SAIDA = @NF_NUMERO, FILIAL = @FILIAL, SERIE_NF = @SERIE_NF, MENSAGEM = @MENSAGEM WHERE ID_NOTA = @ID_NOTA

    COMMIT
    
    GOTO PROXIMO

    PROXIMO:
    	FETCH NEXT FROM CUR_PED INTO @ID_NOTA, @PEDIDO, @VALOR_PLANILHA, @CENTRO_CUSTO 
END

CLOSE CUR_PED 
DEALLOCATE CUR_PED 

