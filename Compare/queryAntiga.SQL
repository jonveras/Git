			INNER JOIN W_GS_FILIAIS_CONTA_CONTABIL_MUTUO B (NOLOCK) ON C.COD_FILIAL = B.COD_FILIAL AND A.CONTA_CONTABIL = B.CONTA_CONTABIL
		) > 0
	BEGIN
