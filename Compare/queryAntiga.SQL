DECLARE @XML VARCHAR(MAX), @CHAVE_NFE VARCHAR(44)

--- LOJAS (RETAGUARDA)
DECLARE XCURSOR CURSOR FAST_FORWARD FOR

	SELECT A.CHAVE_NFE
	FROM LOJA_NOTA_FISCAL A (NOLOCK)
	LEFT JOIN DADOS_CADASTRO_XML_NFE B (NOLOCK) ON A.CHAVE_NFE = B.CHAVE_NFE
	JOIN LOJAS_VAREJO (NOLOCK) F ON A.CODIGO_FILIAL = F.CODIGO_FILIAL
	WHERE A.STATUS_NFE IN ('5','49') AND A.SERIE_NF <> '5'
	AND A.SERIE_NF NOT IN (SELECT SERIE_NF FROM SERIES_NF (NOLOCK) WHERE ESPECIE_SERIE = '65' )
	AND EMISSAO BETWEEN DATEADD(MM,-1,DATEADD(DD,-DAY(GETDATE())+1,GETDATE())) AND GETDATE()
	AND B.CHAVE_NFE IS NULL

OPEN XCURSOR
FETCH NEXT FROM XCURSOR INTO @CHAVE_NFE
WHILE @@FETCH_STATUS = 0
BEGIN
	SELECT @XML=[XML] FROM [192.168.9.205].[4hitNFe].dbo.tb_Integracao WHERE (CHAVE_ACESSO=@CHAVE_NFE or CHAVE_ORIGINAL=@CHAVE_NFE)
	IF @XML IS NULL
		SELECT @XML=[XML] FROM [4hitNFe].dbo.tb_Integracao WHERE (CHAVE_ACESSO=@CHAVE_NFE or CHAVE_ORIGINAL=@CHAVE_NFE)
	IF @XML IS NOT NULL
		EXEC GS_PREENCHER_DADOS_CADASTRO_XML_NFE  @XML,@CHAVE_NFE

	FETCH NEXT FROM XCURSOR INTO @CHAVE_NFE
END
CLOSE XCURSOR
DEALLOCATE XCURSOR


