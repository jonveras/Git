	--) > 0

	--BEGIN

	--	  SELECT  @ERRNO=30002,

	--	   @ERRMSG='RATEIO DE FILIAL COM MATRIZ CONTÁBIL DIFERENTE DO CABEÇALHO DO LANCAMENTO. OPERAÇÃO CANCELADA.'

	--	   GOTO ERROR

	--END

/**/



--/*31/07/2014 - ISMARA - NÃO PERMITIR SALVAR LANÇAMENTOS COM CONTA CONTABIL INATIVA*/

--	IF (

